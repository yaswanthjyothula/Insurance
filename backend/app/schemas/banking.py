from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class BankProfile(BaseModel):
    id: str = Field(..., description="Unique bank profile ID, e.g. hdfc_salary")
    bank_name: str = Field(..., description="Name of the financial institution")
    bank_code: str = Field(..., description="HDFC, ICICI, SBI, AXIS")
    account_type: str = Field(..., description="e.g. Corporate Classic Salary Account")
    masked_account: str = Field(..., description="e.g. •••• 4819")
    holder_name: str = Field(..., description="Primary account holder")
    kyc_status: str = Field("Verified (CKYC Compliant)", description="KYC status")
    cibil_score: int = Field(..., description="Credit score from bureau feed")
    monthly_salary_credit: float = Field(..., description="Average monthly salary credit in INR")
    annual_income: float = Field(..., description="Annualized gross income in INR")
    monthly_expenses_inferred: float = Field(..., description="Monthly recurring living debits in INR")
    annual_expenses: float = Field(..., description="Annualized living expenses in INR")
    age: int = Field(..., description="Age derived from KYC records")
    employment_type: str = Field("salaried", description="Employment classification")
    dependents_count: int = Field(..., description="Declared dependents")
    active_home_loan_balance: float = Field(0.0, description="Outstanding home mortgage balance")
    active_other_loans_balance: float = Field(0.0, description="Outstanding vehicle/personal loan balance")
    liquid_savings_balance: float = Field(..., description="Total savings + sweep FDs in INR")
    existing_term_cover: float = Field(0.0, description="Active corporate/individual term cover")
    support_horizon_years: int = Field(20, description="Recommended family dependency years")
    buffer_months: int = Field(6, description="Emergency reserve months")
    retirement_age: int = Field(60, description="Planned retirement age")
    smoker_status: str = Field("no", description="yes/no")
    future_goals: List[Dict[str, Any]] = Field(default_factory=list)
    verification_badge: str = Field(..., description="Account Aggregator verification source")
    consent_statement: str = Field(..., description="RBI-compliant consent description")
